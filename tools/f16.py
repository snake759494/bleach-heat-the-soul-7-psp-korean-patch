def decode(w):
    return ''.join('　' if v == SPACE else CH.get(v, '〓') for v in w)


def slots(d):
    """yield (byte offset, words) for every 24-byte slot holding a string"""
    for o in range(0, len(d) - 23, 24):
        w = struct.unpack_from('<12H', d, o)
        s = 2 if o == 0 else 0
        if w[s] in (0xfffe, 0xffff):
            continue
        out = []
        for v in w[s:]:
            if v in (0xfffe, 0xffff):
                break
            out.append(v)
        yield o + 2 * s, out
